// Builds supabase/seed.sql (service catalog) from ../data/services.json
import { readFileSync, writeFileSync } from 'node:fs';
const here = new URL('.', import.meta.url);
const data = JSON.parse(readFileSync(new URL('../../data/services.json', here), 'utf8'));
export const slugify = (s) => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = [];
const seen = new Set();
for (const t of data.trades) for (const g of t.groups) for (const [name, , lo, hi, unit, flags = ''] of g.items) {
  let id = slugify(name); if (seen.has(id)) id = `${t.id}-${id}`; seen.add(id);
  rows.push(`(${q(id)},${q(t.id)},${q(g.name)},${q(name)},${lo},${hi},${q(unit || 'job')},${flags.includes('P')},${flags.includes('E')},${flags.includes('H')})`);
}
writeFileSync(new URL('../supabase/seed.sql', here),
  `-- generated by scripts/gen-seed.mjs; do not edit by hand\ninsert into public.services (id, trade, group_name, name, price_low, price_high, unit, needs_permit, emergency, handyman_ok) values\n${rows.join(',\n')}\non conflict (id) do update set trade = excluded.trade, group_name = excluded.group_name, name = excluded.name, price_low = excluded.price_low, price_high = excluded.price_high, unit = excluded.unit, needs_permit = excluded.needs_permit, emergency = excluded.emergency, handyman_ok = excluded.handyman_ok;\n`);
console.log(`seed.sql: ${rows.length} services`);
